const dictionaries: Record<UiLanguage, TapeCopy> = { en, de, fr, es, it, nl, pl, ar, pt };

export function tapeCopy(language: UiLanguage) {
  return dictionaries[language] ?? en;
}

export function fillTape(template: string, vars: Record<string, string | number>) {
  return template.replace(/\{(\w+)\}/g, (_, key: string) => String(vars[key] ?? ""));
}

export function countLine(n: number, one: string, many: string, extra: Record<string, string | number> = {}) {
  return fillTape(n === 1 ? one : many, { n, ...extra });
}
